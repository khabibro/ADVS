"""Submission bundles: multi-document test cases exercising PROJECT-level
validation (APPLICANT_NAME_MATCH, COMPANY_NAME_MATCH, DUPLICATE_DOCUMENT,
REQUIRED_DOCUMENT) rather than single-document extraction. Each bundle
references sample_ids of dedicated fixtures generated by
`eval_lib.generate.generate_submission_documents` (controlled name/company
identity, valid/expired/near-expiry dates) -- chosen deliberately rather
than hoping generic pool samples happen to share an identity by chance.

Every bundle traces to one of the required scenarios (see
evaluation/README.md): READY, missing required document, expired document,
applicant mismatch, company mismatch, duplicate document, a per-document
REVIEW_REQUIRED rolling up to bundle REVIEW_REQUIRED, and an ambiguous/wrong document
submitted in place of a required type.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass
from typing import Any

ALL_REQUIRED_TYPES = [
    "GRADUATION_CERTIFICATE",
    "CAREER_CERTIFICATE",
    "BUSINESS_REGISTRATION_CERTIFICATE",
    "SME_CONFIRMATION_CERTIFICATE",
]


@dataclass
class SubmissionBundle:
    bundle_id: str
    description: str
    applicant_name: str | None
    company_name: str | None
    required_document_types: list[str]
    document_sample_ids: list[str]
    expected_status: str
    reason: str

    def to_json(self) -> dict[str, Any]:
        return asdict(self)

    @staticmethod
    def from_json(payload: dict[str, Any]) -> SubmissionBundle:
        return SubmissionBundle(**payload)


